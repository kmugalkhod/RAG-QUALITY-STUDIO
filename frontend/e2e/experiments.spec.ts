import { test, expect } from '@playwright/test';

test('import reviewed dataset, compare two versions and inspect evidence', async ({ page, request }) => {
  test.skip(process.env.E2E_EMBEDDING_FIXTURE !== '1', 'Requires isolated deterministic providers.');
  test.setTimeout(180000);
  page.setDefaultTimeout(15000);
  const project = await (await request.post('/api/projects', { data: { name: `Experiments ${Date.now()}` } })).json();
  await page.goto(`/#/projects/${project.id}/knowledge-base`);
  await page.getByRole('button', { name: 'Add document', exact: true }).click();
  await page.getByLabel('PDF or UTF-8 TXT').setInputFiles({ name: 'orchard.txt', mimeType: 'text/plain', buffer: Buffer.from('The orchard grows apples. Harvest begins in September.') });
  await page.getByRole('button', { name: 'Upload document', exact: true }).click();
  await page.getByRole('button', { name: 'Start processing', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Inspect 1 chunks' })).toBeVisible({ timeout: 30000 });
  await page.getByRole('button', { name: 'Indexes', exact: true }).click();
  await page.getByRole('button', { name: 'Index documents' }).click();
  await expect(page.getByRole('button', { name: 'Use index 1' })).toBeVisible({ timeout: 30000 });
  const index = (await (await request.get(`/api/projects/${project.id}/indexes`)).json()).items[0];
  const nodes = [{ id: 'q', type: 'question' }, { id: 'r', type: 'retriever', index_id: index.id, top_k: 1 }, { id: 'p', type: 'prompt', template: '{question} {context}' }, { id: 'l', type: 'llm', model: 'test/chat', temperature: 0, max_tokens: 512 }, { id: 'a', type: 'answer' }];
  const payload = { name: 'Orchard comparison', execution: { schema_version: 1, nodes, edges: nodes.slice(1).map((n,i) => ({ source: nodes[i].id, target: n.id })) }, layout: { positions: Object.fromEntries(nodes.map((n,i) => [n.id, { x: 0, y: i*120 }])) } };
  const first = await (await request.post(`/api/projects/${project.id}/pipelines`, { data: payload })).json();
  nodes[1].top_k = 2;
  const second = await (await request.post(`/api/projects/${project.id}/pipelines/${first.pipeline_id}/versions`, { data: payload })).json();
  await page.getByRole('link', { name: 'Experiments', exact: true }).click();
  await page.getByLabel('Dataset name', { exact: true }).fill('Reviewed orchard');
  await page.getByLabel('CSV file').setInputFiles({ name: 'reviewed.csv', mimeType: 'text/csv', buffer: Buffer.from('question,reference_answer\nWhat does the orchard grow?,The orchard grows apples.\nWhat is the launch code?,\nWhen is the harvest?,Harvest begins in September.\n') });
  await page.getByRole('button', { name: 'Preview CSV', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Preview · 3 questions' })).toBeVisible();
  await page.getByRole('button', { name: 'Import reviewed dataset' }).click();
  await expect(page.getByText('Imported Reviewed orchard version 1.', { exact: true })).toBeVisible();
  await page.getByLabel('Experiment name', { exact: true }).fill('Two saved versions');
  await page.getByRole('combobox', { name: 'Candidate A', exact: true }).selectOption(first.id);
  await page.getByRole('combobox', { name: 'Candidate B (optional)', exact: true }).selectOption(second.id);
  await page.getByRole('button', { name: 'Run experiment', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Two saved versions' })).toBeVisible();
  await expect(page.getByRole('status')).toContainText('succeeded · 6 / 6', { timeout: 150000 });
  await expect(page.getByRole('heading', { name: 'Paired comparison' })).toBeVisible();
  await page.getByRole('button', { name: 'What does the orchard grow?', exact: true }).click();
  const evidence = page.getByRole('region', { name: 'Question evidence' });
  await expect(evidence.getByText('The orchard grows apples. [S1]', { exact: true })).toHaveCount(2);
  await expect(evidence.getByText('The orchard grows apples. Harvest begins in September.', { exact: true })).toHaveCount(2);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/experiments-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/experiments-mobile.png', fullPage: true });
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Two saved versions' })).toBeVisible();
});
